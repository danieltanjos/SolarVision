-- Coletor dos eventos de uso do app (datalake/docs/CONTRATO_EVENTO.md).
-- 1. eventos_coletados: o app grava os eventos em lotes (só insert); o datalake/coletor/coletar_supabase.py
--    lê com a service key e leva para a landing do datalake. Ninguém lê pela API, nem o próprio usuário.
-- 2. usuarios.rastreamento: o opt-out do rastreamento, editável em Configurações.

-- 1. Eventos. O conteúdo não é validado aqui de propósito: quem valida é a Silver do datalake, que separa
--    o evento inválido com o motivo (R7). Aqui só se barra o que não é um evento ou é grande demais.
create table public.eventos_coletados (
    id bigint generated by default as identity primary key,
    evento jsonb not null,
    recebido_em timestamptz not null default now(),
    constraint ck_eventos_coletados_objeto check (
        jsonb_typeof(evento) = 'object' and evento ? 'event_id' and evento ? 'event_name'),
    constraint ck_eventos_coletados_tamanho check (pg_column_size(evento) <= 8192)
);

-- o coletor lê em ordem de chegada, a partir do último id já levado para a landing
create index idx_eventos_coletados_recebido_em on public.eventos_coletados (recebido_em);

alter table public.eventos_coletados enable row level security;
-- Também anon: as telas de login e de criar conta geram eventos antes de existir sessão.
create policy "app envia eventos" on public.eventos_coletados
    for insert to anon, authenticated
    with check (true);
revoke all on public.eventos_coletados from anon, authenticated;
grant insert on public.eventos_coletados to anon, authenticated;

-- 2. Opt-out. Desligado, o app não cria nem envia eventos daquele usuário (lib/tracking.js).
alter table public.usuarios
    add column rastreamento boolean not null default true;

grant update (rastreamento) on public.usuarios to authenticated;
